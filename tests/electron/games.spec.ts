import { test, expect } from '@playwright/test'
import { launchTestApp } from '../helpers/electron-app'
test('game library edits progress and keeps play history with unknown duration and linked plan', async () => {
  const t = await launchTestApp(); try {
    await t.page.getByRole('navigation').getByRole('button', { name: '游戏娱乐', exact: true }).click()
    await expect(t.page.getByLabel('新游戏名称')).toBeVisible()
    await t.page.getByLabel('新游戏名称').fill('星际探索')
    await t.page.getByRole('button', { name: '添加游戏', exact: true }).click()
    await t.page.getByLabel('游戏状态').selectOption('playing')
    await t.page.getByLabel('游戏当前进度').fill('第二章，正在寻找信标')
    await t.page.getByLabel('游戏心得').fill('探索路线值得记录')
    await t.page.getByRole('button', { name: '保存游戏资料', exact: true }).click()
    await expect(t.page.getByRole('status')).toContainText('游戏资料已保存')
    await t.page.getByLabel('当次游玩进展').fill('独特关键词：找到环形信标')
    await t.page.getByRole('button', { name: '保存游玩记录', exact: true }).click()
    await expect(t.page.getByRole('article', { name: '游玩记录' })).toContainText('时长未记录')
    const [session] = await t.page.evaluate(() => window.aia.records.list({ kind: 'play_session' }))
    expect(session.record.data.durationMin).toBeNull()
    const [game] = await t.page.evaluate(() => window.aia.records.list({ kind: 'game' }))
    expect(session.record.data.gameId).toBe(game.record.id)
    expect(game.record.data.progress).toBe('第二章，正在寻找信标')
    await t.page.getByRole('button', { name: '加入今日计划', exact: true }).click()
    await expect(t.page.getByRole('status')).toContainText('已加入今日计划')
    await t.page.getByRole('navigation').getByRole('button', { name: '首页总览', exact: true }).click()
    await expect(t.page.getByRole('button', { name: '打开档案：星际探索', exact: true })).toBeVisible()
    await t.page.getByRole('textbox', { name: '全局关键词搜索' }).fill('环形信标')
    await t.page.getByRole('textbox', { name: '全局关键词搜索' }).press('Enter')
    const found = await t.page.evaluate(() => window.aia.search.query({ query: '环形信标' }))
    expect(found.items[0].recordId).toBe(session.record.id)
    await expect(t.page.getByRole('button', { name: '打开档案：星际探索 · 游玩记录' })).toBeVisible()
  } finally { await t.close() }
})
