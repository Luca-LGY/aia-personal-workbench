import { test, expect } from '@playwright/test'
import { writeFile, readFile } from 'node:fs/promises'
import { join } from 'node:path'
import { launchTestApp } from '../helpers/electron-app'
import { makeRecord } from '../../src/shared/schemas'
test('numbered experiment keeps identity after title edit, links results, excludes templates and schedules next step', async () => {
  const t = await launchTestApp(); try {
    await t.page.getByRole('navigation').getByRole('button', { name: '科研实验', exact: true }).click()
    await expect(t.page.getByLabel('新课题名称')).toBeVisible()
    await t.page.getByLabel('新课题名称').fill('扩散方程数值验证')
    await t.page.getByRole('button', { name: '创建课题', exact: true }).click()
    await t.page.getByLabel('课题进展摘要').fill('正在核对边界条件')
    await t.page.getByRole('button', { name: '保存课题进展', exact: true }).click()
    await expect(t.page.getByRole('status')).toContainText('课题进展已保存')
    await t.page.getByLabel('实验固定编号').fill('EXP-2026-017')
    await t.page.getByLabel('实验标题').fill('第一组网格检验')
    await t.page.getByLabel('实验目的').fill('比较误差随网格的变化')
    await t.page.getByLabel('实验参数JSON').fill('{"网格":128,"步长":0.01}')
    await t.page.getByLabel('实验实际状态').selectOption('running')
    await t.page.getByLabel('实验结果').fill('已获得三组误差数据')
    await t.page.getByLabel('实验下一步').fill('增加一组细网格')
    await t.page.getByLabel('代码版本').fill('solver-v0.2')
    const file = join(t.temp, 'result.csv'); await writeFile(file, 'grid,error\n128,0.01\n')
    await t.app.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, file)
    await t.page.getByRole('button', { name: '关联结果附件', exact: true }).click()
    await expect(t.page.getByText('result.csv', { exact: true })).toBeVisible()
    await t.page.getByRole('button', { name: '保存实验', exact: true }).click()
    await expect(t.page.getByRole('article', { name: '实验：EXP-2026-017' })).toContainText('结论尚未记录')
    const [v] = await t.page.evaluate(() => window.aia.records.list({ kind: 'experiment', role: 'actual' }))
    expect(v.record.data.conclusion).toBe('')
    const attachment = await t.page.evaluate(id => window.aia.attachments.resolve(id), v.record.attachmentIds[0])
    expect(attachment?.name).toBe('result.csv'); expect(await readFile(join(t.archiveRoot, attachment!.path), 'utf8')).toBe('grid,error\n128,0.01\n')
    const template = makeRecord('experiment', { title: '他人模板', module: 'research', role: 'template', data: { experimentNo: 'TEMPLATE', status: 'planned' } })
    await t.page.evaluate(record => window.aia.records.save({ record, expectedHash: null }), template)
    await expect(t.page.getByText('本人实验 1', { exact: true })).toBeVisible()
    await t.page.getByRole('article', { name: '实验：EXP-2026-017' }).getByRole('button', { name: '编辑实验', exact: true }).click()
    await t.page.getByLabel('实验标题').fill('细网格误差检验')
    await t.page.getByRole('button', { name: '保存实验', exact: true }).click()
    await expect(t.page.getByRole('article', { name: '实验：EXP-2026-017' })).toContainText('细网格误差检验')
    await t.page.getByRole('article', { name: '实验：EXP-2026-017' }).getByRole('button', { name: '加入今日计划', exact: true }).click()
    await expect(t.page.getByRole('status')).toContainText('已加入今日计划')
    await t.page.getByRole('textbox', { name: '全局关键词搜索' }).fill('EXP-2026-017')
    await t.page.getByRole('textbox', { name: '全局关键词搜索' }).press('Enter')
    await t.page.getByRole('button', { name: '打开档案：细网格误差检验' }).click()
    await expect(t.page.getByRole('button', { name: '打开附件：result.csv' })).toBeVisible()
    const found = await t.page.evaluate(id => window.aia.records.get(id), v.record.id)
    expect(found?.record.title).toBe('细网格误差检验')
  } finally { await t.close() }
})
