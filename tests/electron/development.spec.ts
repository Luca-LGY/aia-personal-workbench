import { test, expect } from '@playwright/test'
import { launchTestApp } from '../helpers/electron-app'
test('development project keeps explicit repository link after rename and tracks issues, versions and next step', async () => {
  const t = await launchTestApp(); try {
    await t.page.getByRole('navigation').getByRole('button', { name: '开发工作', exact: true }).click()
    await expect(t.page.getByLabel('新开发项目名称')).toBeVisible()
    await t.page.getByLabel('新开发项目名称').fill('我的数值工具')
    await t.page.getByRole('button', { name: '创建开发项目', exact: true }).click()
    await t.page.getByLabel('项目仓库地址').fill('https://github.com/example/different-repo')
    await t.page.getByLabel('开发阶段').fill('验证阶段')
    await t.page.getByLabel('开发当前目标').fill('完成稳定性检验')
    await t.page.getByLabel('开发下一步').fill('处理边界误差')
    await t.page.getByRole('button', { name: '保存项目资料', exact: true }).click()
    await expect(t.page.getByRole('status',{name:'操作提示'})).toContainText('项目资料已保存')
    const [project] = await t.page.evaluate(() => window.aia.records.list({ kind: 'dev_project' }))
    await t.page.getByLabel('开发项目名称', { exact: true }).fill('重新命名的工具')
    await t.page.getByRole('button', { name: '保存项目资料', exact: true }).click()
    await expect(t.page.getByRole('heading', { name: '重新命名的工具', exact: true })).toBeVisible()
    await t.page.getByLabel('开发问题标题').fill('边界震荡')
    await t.page.getByLabel('开发问题说明').fill('独特关键词：网格边缘出现振荡')
    await t.page.getByRole('button', { name: '添加项目问题', exact: true }).click()
    await expect(t.page.getByLabel('问题状态：边界震荡')).toBeVisible()
    await t.page.getByLabel('问题状态：边界震荡').selectOption('in_progress')
    await expect(t.page.getByRole('status',{name:'操作提示'})).toContainText('问题状态已保存')
    await t.page.getByLabel('项目版本号').fill('v0.2.0')
    await t.page.getByLabel('版本变化说明').fill('加入边界检查')
    await t.page.getByRole('button', { name: '记录项目版本', exact: true }).click()
    await expect(t.page.getByText('v0.2.0', { exact: true })).toBeVisible()
    await t.page.getByRole('button', { name: '加入今日计划', exact: true }).click()
    await expect(t.page.getByRole('status',{name:'操作提示'})).toContainText('已加入今日计划')
    const current = await t.page.evaluate(id => window.aia.records.get(id), project.record.id)
    expect(current?.record.title).toBe('重新命名的工具')
    expect(current?.record.data.repoUrl).toBe('https://github.com/example/different-repo')
    const [issue] = await t.page.evaluate(() => window.aia.records.list({ kind: 'dev_issue' }))
    expect(issue.record.data).toMatchObject({ projectId: project.record.id, status: 'in_progress' })
    const [version] = await t.page.evaluate(() => window.aia.records.list({ kind: 'dev_version' }))
    expect(version.record.data.projectId).toBe(project.record.id)
    const search = await t.page.evaluate(() => window.aia.search.query({ query: '网格边缘' }))
    expect(search.items[0].recordId).toBe(issue.record.id)
    await expect(t.page.getByRole('button', { name: '打开项目仓库', exact: true })).toBeVisible()
  } finally { await t.close() }
})
